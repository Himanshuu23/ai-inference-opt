"""Parse Nsight Systems sqlite exports (+ optional Nsight Compute CSVs) into results/profile_summary.md.

    python scripts/analyze_profile.py [--results-dir results]

Per report: top-10 kernels by GPU time, kernel launches per inference, GPU idle time between kernels,
memcpy/memset time. Everything is computed from the exported sqlite; nothing is estimated.
"""
from __future__ import annotations

import argparse
import csv
import json
import sqlite3
from pathlib import Path

CONFIG_NAMES = {"A": "PyTorch eager FP32", "B": "PyTorch FP16 (cudnn.benchmark)", "C": "torch.compile FP16",
                "D": "TensorRT FP16", "E": "TensorRT INT8"}


def _cols(con, table):
    return [r[1] for r in con.execute(f"PRAGMA table_info({table})")]


def _has(con, table):
    return con.execute("SELECT 1 FROM sqlite_master WHERE name=?", (table,)).fetchone() is not None


def merged_busy(intervals):
    """Total length of the union of [start,end] intervals (ns)."""
    busy, cur_s, cur_e = 0, None, None
    for s, e in sorted(intervals):
        if cur_e is None or s > cur_e:
            if cur_e is not None:
                busy += cur_e - cur_s
            cur_s, cur_e = s, e
        else:
            cur_e = max(cur_e, e)
    if cur_e is not None:
        busy += cur_e - cur_s
    return busy


def analyse_sqlite(path: Path, iters: int) -> dict:
    con = sqlite3.connect(str(path))
    res = {"iters": iters}
    if not _has(con, "CUPTI_ACTIVITY_KIND_KERNEL"):
        res["error"] = "no kernel table in export (capture range empty? profiler API not reached?)"
        return res
    kc = _cols(con, "CUPTI_ACTIVITY_KIND_KERNEL")
    namecol = "demangledName" if "demangledName" in kc else "shortName"
    q = (f"SELECT k.start, k.end, COALESCE(s.value, CAST(k.{namecol} AS TEXT)) "
         f"FROM CUPTI_ACTIVITY_KIND_KERNEL k LEFT JOIN StringIds s ON s.id = k.{namecol}")
    ks = con.execute(q).fetchall()
    if not ks:
        res["error"] = "kernel table is empty"
        return res
    res["n_kernels"] = len(ks)
    res["kernels_per_inf"] = len(ks) / iters
    t0, t1 = min(k[0] for k in ks), max(k[1] for k in ks)
    busy = merged_busy([(k[0], k[1]) for k in ks])
    res["window_ms"] = (t1 - t0) / 1e6
    res["kernel_busy_ms"] = busy / 1e6
    res["idle_ms"] = (t1 - t0 - busy) / 1e6
    res["idle_pct"] = 100.0 * (t1 - t0 - busy) / (t1 - t0)
    res["window_ms_per_inf"] = res["window_ms"] / iters
    res["idle_ms_per_inf"] = res["idle_ms"] / iters
    agg = {}
    for s, e, n in ks:
        a = agg.setdefault(n, [0, 0])
        a[0] += e - s
        a[1] += 1
    tot = sum(v[0] for v in agg.values())
    res["top"] = [(n, v[0] / 1e6, v[1], 100.0 * v[0] / tot) for n, v in sorted(agg.items(), key=lambda kv: -kv[1][0])[:10]]
    res["distinct_kernels"] = len(agg)
    # memcpy / memset
    mc_ms, mc_bytes, mc_n = 0.0, 0, 0
    if _has(con, "CUPTI_ACTIVITY_KIND_MEMCPY"):
        r = con.execute("SELECT COALESCE(SUM(end-start),0), COALESCE(SUM(bytes),0), COUNT(*) FROM CUPTI_ACTIVITY_KIND_MEMCPY").fetchone()
        mc_ms, mc_bytes, mc_n = r[0] / 1e6, r[1], r[2]
    ms_ms, ms_n = 0.0, 0
    if _has(con, "CUPTI_ACTIVITY_KIND_MEMSET"):
        r = con.execute("SELECT COALESCE(SUM(end-start),0), COUNT(*) FROM CUPTI_ACTIVITY_KIND_MEMSET").fetchone()
        ms_ms, ms_n = r[0] / 1e6, r[1]
    res.update(memcpy_ms=mc_ms, memcpy_bytes=mc_bytes, memcpy_n=mc_n, memset_ms=ms_ms, memset_n=ms_n)
    con.close()
    return res


def parse_ncu_csv(path: Path):
    """ncu --csv output: some log lines, then a header starting with "ID". Returns (kernel_name, {metric: (value, unit)})."""
    lines = path.read_text(errors="ignore").splitlines()
    start = next((i for i, l in enumerate(lines) if l.startswith('"ID"')), None)
    if start is None:
        return None, {}
    rows = list(csv.DictReader(lines[start:]))
    if not rows:
        return None, {}
    return rows[0].get("Kernel Name", "?"), {r["Metric Name"]: (r["Metric Value"], r["Metric Unit"]) for r in rows}


def md_report(rdir: Path) -> str:
    out = ["# Profile summary", "",
           "_Generated by `scripts/analyze_profile.py` from Nsight exports on this machine. No values are estimated._", ""]
    reports = sorted((rdir / "nsys").glob("*.sqlite"))
    results = {}
    for p in reports:
        meta_p = p.parent / (p.stem + ".meta.json")
        if not meta_p.exists():
            out.append(f"- TODO: `{p.name}` has no `{meta_p.name}` sidecar (iteration count unknown); skipped.")
            continue
        meta = json.loads(meta_p.read_text())
        results[p.stem] = (meta, analyse_sqlite(p, meta["iters"]))

    if not results:
        out += ["## Nsight Systems", "",
                "TODO: no `results/nsys/*.sqlite` found. Run `bash scripts/profile_nsys.sh` "
                "(see README 'Profiling permissions' if nsys complains about permissions).", ""]
    else:
        out += ["## Overview (ResNet-50, batch 16, per inference = per forward pass of the whole batch)", "",
                "| report | config | kernels / inference | distinct kernels | GPU window / inf (ms) | idle between kernels / inf (ms) | idle % | memcpy (ms total) | memcpy bytes | memset (ms total) |",
                "|---|---|---|---|---|---|---|---|---|---|"]
        for tag, (meta, r) in results.items():
            if "error" in r:
                out.append(f"| {tag} | {meta['config']} | ERROR: {r['error']} | | | | | | | |")
                continue
            out.append(f"| {tag} | {meta['config']} ({CONFIG_NAMES.get(meta['config'], '')}) | {r['kernels_per_inf']:.1f} | {r['distinct_kernels']} | "
                       f"{r['window_ms_per_inf']:.3f} | {r['idle_ms_per_inf']:.3f} | {r['idle_pct']:.1f} | "
                       f"{r['memcpy_ms']:.3f} | {r['memcpy_bytes']} | {r['memset_ms']:.3f} |")
        out.append("")
        # Fusion comparison
        ok = {m["config"]: r for m, r in results.values() if "error" not in r}
        if "A" in ok and "D" in ok:
            a, d = ok["A"], ok["D"]
            out += ["## Layer fusion: eager vs TensorRT", "",
                    f"- PyTorch eager FP32 (A): **{a['kernels_per_inf']:.1f}** kernel launches per inference",
                    f"- TensorRT FP16 (D): **{d['kernels_per_inf']:.1f}** kernel launches per inference "
                    f"({a['kernels_per_inf'] / d['kernels_per_inf']:.2f}x fewer than A)",
                    f"- GPU idle time between kernels per inference: A {a['idle_ms_per_inf']:.3f} ms vs D {d['idle_ms_per_inf']:.3f} ms",
                    "- Interpretation: see README 'Findings' (conv+BN+ReLU fusion, removal of standalone elementwise kernels).", ""]
        for tag, (meta, r) in results.items():
            if "error" in r:
                continue
            out += [f"## Top 10 kernels by GPU time: `{tag}`", "",
                    "| # | kernel | total ms | launches | % of kernel time |", "|---|---|---|---|---|"]
            for i, (n, ms, c, pct) in enumerate(r["top"], 1):
                n = n.replace("|", "\\|")
                out.append(f"| {i} | `{n[:100]}{'...' if len(n) > 100 else ''}` | {ms:.3f} | {c} | {pct:.1f} |")
            out.append("")

    out += ["## Nsight Compute (optional, N=1)", ""]
    ncus = sorted((rdir / "ncu").glob("*.csv"))
    if not ncus:
        out += ["TODO: no `results/ncu/*.csv`. Run `bash scripts/profile_ncu.sh` (needs ncu + profiling permissions).", ""]
    for p in ncus:
        name, m = parse_ncu_csv(p)
        if not m:
            out += [f"- TODO: `{p.name}` contained no metrics (kernel filter matched nothing, or permission error: see the file).", ""]
            continue
        out += [f"### `{p.name}`", "", f"Kernel: `{(name or '?')[:120]}`", "", "| metric | value | unit |", "|---|---|---|"]
        out += [f"| {k} | {v[0]} | {v[1]} |" for k, v in m.items()]
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--results-dir", default=str(Path(__file__).resolve().parents[1] / "results"))
    a = ap.parse_args()
    rdir = Path(a.results_dir)
    text = md_report(rdir)
    (rdir / "profile_summary.md").write_text(text)
    print(text)
    print(f"\nwritten: {rdir / 'profile_summary.md'}")
